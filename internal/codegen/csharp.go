package codegen

import (
	"fmt"
	"sort"
	"strings"

	"github.com/miyako/OpenAPI/internal/openapi"
)

// GenerateCSharp exports C# class models with System.Text.Json attributes from an OpenAPI 3.1 specification.
func GenerateCSharp(spec *openapi.OpenAPISpec, namespace string) string {
	if namespace == "" {
		namespace = "FourD.OpenAPI.Models"
	}

	var sb strings.Builder

	sb.WriteString("// <auto-generated>\n")
	sb.WriteString(fmt.Sprintf("// %s — C# / .NET Models\n", spec.Info.Title))
	sb.WriteString(fmt.Sprintf("// Version: %s\n", spec.Info.Version))
	sb.WriteString("// Generated automatically by 4d-openapi\n")
	sb.WriteString("// </auto-generated>\n\n")
	sb.WriteString("#nullable enable\n\n")
	sb.WriteString("using System;\n")
	sb.WriteString("using System.Collections.Generic;\n")
	sb.WriteString("using System.Text.Json.Serialization;\n\n")
	sb.WriteString(fmt.Sprintf("namespace %s\n{\n", namespace))

	schemaNames := make([]string, 0, len(spec.Components.Schemas))
	for name := range spec.Components.Schemas {
		schemaNames = append(schemaNames, name)
	}
	sort.Strings(schemaNames)

	for _, name := range schemaNames {
		sch := spec.Components.Schemas[name]
		sb.WriteString(renderCSharpClass(name, sch))
		sb.WriteString("\n\n")
	}

	sb.WriteString("}\n")
	return sb.String()
}

func renderCSharpClass(name string, sch *openapi.Schema) string {
	var sb strings.Builder

	if sch.Description != "" {
		sb.WriteString(fmt.Sprintf("    /// <summary>\n    /// %s\n    /// </summary>\n", sch.Description))
	}
	sb.WriteString(fmt.Sprintf("    public class %s\n    {\n", name))

	requiredMap := make(map[string]bool)
	for _, r := range sch.Required {
		requiredMap[r] = true
	}

	propNames := make([]string, 0, len(sch.Properties))
	for pn := range sch.Properties {
		propNames = append(propNames, pn)
	}
	sort.Strings(propNames)

	for _, pn := range propNames {
		prop := sch.Properties[pn]
		isRequired := requiredMap[pn]
		csType := mapSchemaToCSharpType(prop, isRequired)
		propName := toCSharpIdentifier(pn)

		if prop.Description != "" {
			sb.WriteString(fmt.Sprintf("        /// <summary>\n        /// %s\n        /// </summary>\n", prop.Description))
		}
		sb.WriteString(fmt.Sprintf("        [JsonPropertyName(\"%s\")]\n", pn))
		sb.WriteString(fmt.Sprintf("        public %s %s { get; set; }\n\n", csType, propName))
	}

	sb.WriteString("    }")
	return sb.String()
}

func toCSharpIdentifier(name string) string {
	if strings.HasPrefix(name, "__") {
		clean := strings.TrimPrefix(name, "__")
		return strings.ToUpper(clean[:1]) + clean[1:]
	}
	if name == "ID" {
		return "Id"
	}
	if len(name) > 0 {
		return strings.ToUpper(name[:1]) + name[1:]
	}
	return name
}

func mapSchemaToCSharpType(sch *openapi.Schema, required bool) string {
	if sch == nil {
		return "object?"
	}

	nullableSuffix := "?"
	if required {
		nullableSuffix = ""
	}

	if sch.Ref != "" {
		parts := strings.Split(sch.Ref, "/")
		return parts[len(parts)-1] + nullableSuffix
	}

	if sch.Type != nil {
		switch t := sch.Type.(type) {
		case string:
			return mapSingleCSharpType(t, sch) + nullableSuffix
		case []string:
			nonNullType := "string"
			for _, st := range t {
				if st != "null" {
					nonNullType = mapSingleCSharpType(st, sch)
				}
			}
			return nonNullType + "?"
		}
	}

	return "object?"
}

func mapSingleCSharpType(t string, sch *openapi.Schema) string {
	switch t {
	case "string":
		if sch.Format == "date" || sch.Format == "date-time" {
			return "DateTime"
		}
		return "string"
	case "integer":
		if sch.Format == "int64" {
			return "long"
		}
		return "int"
	case "number":
		return "double"
	case "boolean":
		return "bool"
	case "array":
		if sch.Items != nil {
			itemType := mapSchemaToCSharpType(sch.Items, true)
			return fmt.Sprintf("List<%s>", itemType)
		}
		return "List<object>"
	case "object":
		return "Dictionary<string, object>"
	default:
		return "object"
	}
}
